import os
import pyogrio


# ============================================================
# 국가표준 LINK SHP 경로
# ============================================================

LINK_FILE = os.path.join(
    "data",
    "national_links",
    "MOCT_LINK.shp"
)


# ============================================================
# 파일 존재 확인
# ============================================================

print()
print("======================================")
print("국가표준 LINK 파일 확인")
print("======================================")

print("파일 경로:", LINK_FILE)
print("파일 존재:", os.path.exists(LINK_FILE))


if not os.path.exists(LINK_FILE):

    print()
    print("MOCT_LINK.shp 파일을 찾을 수 없습니다.")
    print("data/national_links 폴더를 확인해주세요.")

    exit()


# ============================================================
# SHP 메타데이터 읽기
#
# 전국 데이터를 통째로 불러오지 않고
# 필드 / 좌표계 / geometry 타입만 확인
# ============================================================

info = pyogrio.read_info(
    LINK_FILE
)


# ============================================================
# 결과 출력
# ============================================================

print()
print("======================================")
print("국가표준 LINK 데이터 정보")
print("======================================")

print(
    "Geometry 타입:",
    info.get("geometry_type")
)

print(
    "좌표계 CRS:",
    info.get("crs")
)

print(
    "전체 LINK 개수:",
    info.get("features")
)


print()
print("======================================")
print("컬럼 목록")
print("======================================")

fields = info.get(
    "fields",
    []
)


for field in fields:

    print(field)


print()
print("======================================")
print("확인 완료")
print("======================================")